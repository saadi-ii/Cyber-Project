"""Create the RSA key pairs used to sign the Diffie-Hellman public values.

Run once, before starting the server:

    python gen_keys.py

It creates:
  keys/server_private.pem   server.py signs its handshake (keep secret)
  keys/server_public.pem    copy this next to client.py and client_ui.py
  keys/ui_private.pem       client_ui.py signs the browser handshake (keep secret)
  keys/ui_public.pem        the browser's pinned key
  UI/ui_public_key.js       the bridge public key, loaded by the browser page

Existing keys are never overwritten. Delete the keys/ folder to start over.
"""

import base64
import os
import sys

from Crypto.PublicKey import RSA

from config import (
    KEY_DIR, SERVER_PRIVATE_KEY_FILE, SERVER_PUBLIC_KEY_FILE,
    UI_PRIVATE_KEY_FILE, UI_PUBLIC_KEY_FILE
)

RSA_BITS = 3072
UI_KEY_JS = "UI/ui_public_key.js"


def make_pair(private_path, public_path):
    if os.path.exists(private_path):
        print("Exists, skipped:", private_path)
        return RSA.import_key(open(private_path, "rb").read())
    key = RSA.generate(RSA_BITS)
    with open(private_path, "wb") as file:
        file.write(key.export_key())
    with open(public_path, "wb") as file:
        file.write(key.publickey().export_key())
    try:
        os.chmod(private_path, 0o600)
    except OSError:
        pass
    print("Created:", private_path, "and", public_path)
    return key


def main():
    os.makedirs(KEY_DIR, exist_ok=True)
    make_pair(SERVER_PRIVATE_KEY_FILE, SERVER_PUBLIC_KEY_FILE)
    ui_key = make_pair(UI_PRIVATE_KEY_FILE, UI_PUBLIC_KEY_FILE)

    # SubjectPublicKeyInfo (DER) is the format WebCrypto's importKey("spki") expects.
    spki = ui_key.publickey().export_key(format="DER", pkcs=8)
    encoded = base64.b64encode(spki).decode("ascii")
    with open(UI_KEY_JS, "w", encoding="utf-8") as file:
        file.write(
            "// Pinned bridge public key (RSA-PSS). Generated by gen_keys.py.\n"
            f'window.SECURECHAT_UI_KEY_SPKI = "{encoded}";\n'
        )
    print("Wrote", UI_KEY_JS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
